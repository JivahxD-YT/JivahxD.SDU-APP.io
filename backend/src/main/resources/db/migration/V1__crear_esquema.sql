CREATE TABLE sedes (
    id_sede BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sede VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE denuncias (
    id_denuncia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sede BIGINT REFERENCES sedes (id_sede) ON DELETE SET NULL,
    tg_username VARCHAR(100),
    descripcion VARCHAR(500) NOT NULL,
    fecha_evento DATE NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA'
        CHECK (estado IN ('REGISTRADA', 'ADMITIDA', 'RECHAZADA', 'PROCESANDO', 'PROCESADA')),
    rol_denunciante VARCHAR(50) NOT NULL
        CHECK (rol_denunciante IN ('ESTUDIANTE', 'EMPLEADO', 'PROFESOR', 'ADMINISTRATIVO', 'EXTERNO', 'EGRESADO'))
);

CREATE INDEX idx_denuncias_fecha_registro ON denuncias (fecha_registro DESC);
CREATE INDEX idx_denuncias_sede ON denuncias (id_sede);

CREATE TABLE usuarios_telegram (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id VARCHAR(30) NOT NULL UNIQUE,
    tg_usuario VARCHAR(100) NOT NULL UNIQUE,
    tg_nombre VARCHAR(150),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE telegram_sync_state (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    next_update_offset BIGINT NOT NULL DEFAULT 0
);

